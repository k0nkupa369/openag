import { useSyncExternalStore, type CSSProperties } from "react";
import { CircleCheck, Info, LoaderCircle, OctagonX, TriangleAlert } from "lucide-react";
import { Toaster as Sonner, type ToasterProps } from "sonner";

// The desk sets the effective theme on <html data-theme>; follow it so toasts match a manual Light/Dark choice.
function subscribe(onChange: () => void) {
  const observer = new MutationObserver(onChange);
  observer.observe(document.documentElement, { attributes: true, attributeFilter: ["data-theme"] });
  return () => observer.disconnect();
}
const effectiveTheme = (): ToasterProps["theme"] => document.documentElement.dataset.theme === "dark" ? "dark" : "light";

function Toaster(props: ToasterProps) {
  const theme = useSyncExternalStore(subscribe, effectiveTheme, () => "light" as const);
  return (
    <Sonner
      theme={theme}
      className="toaster group"
      icons={{
        success: <CircleCheck className="size-4" />,
        info: <Info className="size-4" />,
        warning: <TriangleAlert className="size-4" />,
        error: <OctagonX className="size-4" />,
        loading: <LoaderCircle className="size-4 animate-spin motion-reduce:animate-none" />,
      }}
      style={{
        "--normal-bg": "var(--popover)",
        "--normal-text": "var(--popover-foreground)",
        "--normal-border": "var(--border)",
        "--border-radius": "var(--radius)",
      } as CSSProperties}
      {...props}
    />
  );
}

export { Toaster };
